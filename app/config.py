"""Configuration management for PocketDrop."""

import os
from pathlib import Path
from typing import Optional


class Settings:
    """Application settings with environment variable overrides and validations."""

    def __init__(
        self,
        base_dir: Optional[Path] = None,
        data_dir: Optional[Path] = None,
        host: Optional[str] = None,
        port: Optional[int] = None,
        max_file_size_bytes: Optional[int] = None,
        max_total_storage_bytes: Optional[int] = None,
        max_text_length: Optional[int] = None,
        auth_token: Optional[str] = None,
    ):
        # Base project directory
        self.BASE_DIR = base_dir or Path(__file__).resolve().parent.parent

        # Data directory configuration
        env_data_dir = os.getenv("POCKETDROP_DATA_DIR")
        if data_dir:
            self.DATA_DIR = Path(data_dir).resolve()
        elif env_data_dir:
            self.DATA_DIR = Path(env_data_dir).resolve()
        else:
            self.DATA_DIR = (self.BASE_DIR / "data").resolve()

        # Dedicated subdirectories
        self.STORAGE_DIR = (self.DATA_DIR / "storage").resolve()
        self.DB_PATH = (self.DATA_DIR / "pocketdrop.db").resolve()

        # Network settings
        self.HOST = host or os.getenv("POCKETDROP_HOST", "127.0.0.1")
        raw_port = port if port is not None else int(os.getenv("POCKETDROP_PORT", "8000"))
        if not (1 <= raw_port <= 65535):
            raise ValueError(f"Port must be between 1 and 65535, got {raw_port}")
        self.PORT = raw_port

        # Quotas and size limits
        raw_max_file = (
            max_file_size_bytes
            if max_file_size_bytes is not None
            else int(os.getenv("POCKETDROP_MAX_FILE_SIZE_BYTES", str(500 * 1024 * 1024)))
        )  # 500 MB default
        if raw_max_file <= 0:
            raise ValueError("max_file_size_bytes must be positive")
        self.MAX_FILE_SIZE_BYTES = raw_max_file

        raw_max_storage = (
            max_total_storage_bytes
            if max_total_storage_bytes is not None
            else int(os.getenv("POCKETDROP_MAX_TOTAL_STORAGE_BYTES", str(10 * 1024 * 1024 * 1024)))
        )  # 10 GB default
        if raw_max_storage <= 0:
            raise ValueError("max_total_storage_bytes must be positive")
        self.MAX_TOTAL_STORAGE_BYTES = raw_max_storage

        raw_max_text = (
            max_text_length
            if max_text_length is not None
            else int(os.getenv("POCKETDROP_MAX_TEXT_LENGTH", "10000"))
        )  # 10,000 characters
        if raw_max_text <= 0:
            raise ValueError("max_text_length must be positive")
        self.MAX_TEXT_LENGTH = raw_max_text

        # Authentication token
        # If not set, can be provided via environment or generated by security module
        self.AUTH_TOKEN = auth_token or os.getenv("POCKETDROP_AUTH_TOKEN")

    def ensure_directories(self) -> None:
        """Create data and storage directories if they do not exist."""
        self.DATA_DIR.mkdir(parents=True, exist_ok=True)
        self.STORAGE_DIR.mkdir(parents=True, exist_ok=True)


# Default singleton instance
settings = Settings()
